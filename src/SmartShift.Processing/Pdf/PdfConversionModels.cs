namespace SmartShift.Processing.Pdf;

/// <summary>
/// Status of a PDF conversion operation reflecting structural completeness and quality limitations.
/// </summary>
public enum PdfConversionStatus
{
    /// <summary>
    /// Conversion finished with full structural reconstruction and verified package integrity.
    /// </summary>
    Successful,

    /// <summary>
    /// Conversion completed, but with documented fidelity limitations (e.g. scanned PDF without OCR embedded as images).
    /// </summary>
    SuccessfulWithLimitations,

    /// <summary>
    /// Conversion failed due to an error, corrupt document, or unrecoverable exception.
    /// </summary>
    Failed,

    /// <summary>
    /// Conversion was cancelled by the user.
    /// </summary>
    Cancelled
}

/// <summary>
/// Structured quality and fidelity report generated by the PDF conversion engine.
/// </summary>
public sealed record PdfConversionQualityReport(
    string SourcePath,
    string? OutputPath,
    IReadOnlyList<string> OutputFiles,
    string ConversionMode,
    int TotalInputPages,
    int PagesProcessed,
    int TotalCharactersExtracted,
    int ImagesPreservedCount,
    int TablesReconstructedCount,
    int HeadingsDetectedCount,
    PdfConversionStatus Status,
    IReadOnlyList<string> Warnings,
    long OutputSizeBytes,
    string SummaryNote)
{
    public bool HasLimitations => Status == PdfConversionStatus.SuccessfulWithLimitations || Warnings.Count > 0;
}
